import assert from 'node:assert/strict';
import { click, reveal, openTool, inspect, rangeSelector } from '../support/controls.mjs';
import { textButton } from '../support/scenario.mjs';
import { until } from '../support/webdriver.mjs';
import { settledPhoto } from './smoke.mjs';

export async function aiMaskPaste(t) {
  await openTool(t,'masks');
  await click(t,'.create-mask');
  await textButton(t,'.shape-menu-list','Select Object');
  const photo=await reveal(t,'svg.mask-svg');
  await t.driver.point(photo.bounds.x+photo.bounds.width*.5,photo.bounds.y+photo.bounds.height*.5);
  await until(()=>t.driver.observe(()=>document.querySelectorAll('.mask-list > li').length===1),'AI object mask created',120000);
  const slider=await reveal(t,rangeSelector('l_exposure'));
  await t.driver.point(slider.x,slider.y);await t.driver.keys(...Array(10).fill('\uE014'));
  await until(async()=>+(await t.driver.observe(inspect,rangeSelector('l_exposure'))).value>.05,'local adjustment applied');
  const value=+(await t.driver.observe(inspect,rangeSelector('l_exposure'))).value;
  await settledPhoto(t);
  await click(t,'[data-action="copy-settings"]');
  await textButton(t,'.copy-settings','Check None');await click(t,'[data-copy-group="masks"]');
  await textButton(t,'.copy-settings .modal-foot','Copy');
  await click(t,'.filmstrip .thumb[title="batch-target-1.jpg"]');
  await settledPhoto(t);
  const other=await reveal(t,'.filmstrip .thumb[title="batch-target-2.jpg"]');
  const modifier=await t.driver.observe(()=>/Mac/.test(navigator.userAgent)?'\uE03D':'\uE009');
  await t.driver.modifiedPoint(modifier,other.x,other.y);
  await click(t,'[data-action="paste-settings"]');
  await until(()=>t.driver.observe(()=>!document.querySelector('[data-batch-paste="busy"]')),'AI paste completes',120000);
  await openTool(t,'masks');
  await until(()=>t.driver.observe(()=>document.querySelectorAll('.mask-list > li').length===1),'pasted object mask');
  assert(Math.abs(+(await t.driver.observe(inspect,rangeSelector('l_exposure'))).value-value)<.02);
  await t.evidence('ai-mask-pasted');
  await click(t,'button[title^="undo ("]');
  await until(()=>t.driver.observe(()=>!document.querySelector('[data-batch-paste="busy"]')),'undo completes',120000);
  await openTool(t,'masks');
  assert.equal(await t.driver.observe(()=>document.querySelectorAll('.mask-list > li').length),0,'undo removes pasted AI mask');
  await click(t,'button[title^="redo ("]');
  await until(()=>t.driver.observe(()=>!document.querySelector('[data-batch-paste="busy"]')),'redo completes',120000);
  await openTool(t,'masks');
  await until(()=>t.driver.observe(()=>document.querySelectorAll('.mask-list > li').length===1),'redo restores AI mask');
  await settledPhoto(t);
  const saved=await t.sidecarsNamed();
  assert(saved.some(s=>s.file==='batch-target-1.jpg.xmp'&&s.text.includes('immage-ai-v1:')),'destination sidecar stores recipe');
  await t.evidence('ai-mask-redone');
  await click(t,'.filmstrip .thumb[title="batch-target-2.jpg"]');await settledPhoto(t);
  await openTool(t,'masks');
  assert.equal(await t.driver.observe(()=>document.querySelectorAll('.mask-list > li').length),1,'second destination retains regenerated mask');
  const calls=((await t.engineLog()).match(/\"cmd\":\"ai_object\"/g)??[]).length;
  await click(t,'button[title^="the previous photo"]');
  await until(async()=>((await t.engineLog()).match(/\"cmd\":\"ai_object\"/g)??[]).length>calls,'Previous runs AI inference',120000);
  await until(()=>t.driver.observe(()=>!document.querySelector('[data-batch-paste="busy"]')),'Previous completes',120000);
  await settledPhoto(t);
  await t.evidence('ai-mask-previous');
  await click(t,'.filmstrip .thumb[title="batch-target-1.jpg"]');await settledPhoto(t);
  await openTool(t,'masks');
  assert.equal(await t.driver.observe(()=>document.querySelectorAll('.mask-list > li').length),1,'reopened destination retains AI mask');
  await click(t,`.filmstrip .thumb[title=${JSON.stringify(t.fixture.file)}]`);
  await settledPhoto(t);
}
