//! One spelling per camera and lens.
//!
//! morfPhoto reads cameras with ExifTool, which gives the raw EXIF strings
//! ("NIKON CORPORATION", "NIKON Z 6"); Immage's own photo cache reads them with
//! darktable, which shows rawspeed's cleaned names ("Nikon", "Z 6"). Values from
//! morfPhoto pass through here so Find lists one entry per camera and lens.
//!
//! Cameras: the table in `data/camera_names.tsv` is darktable's own lookup
//! (`dt_rawspeed_lookup_makermodel`, then libraw's table for CR3), generated by
//! `scripts/gen_camera_names.py` from the pinned darktable. Make and model not in
//! it pass through trimmed, as darktable passes them through. Regenerate it with
//! every darktable pin move.
//!
//! Lenses: darktable reads the lens text from EXIF (exif.cc) and then rewrites
//! Canon RF and RF-S, upper-case NIKKOR / TAMRON / VILTROX names. Those three
//! rules are applied here. Its Sigma rule needs EXIF `LensMake`, which morfPhoto
//! does not mirror, so a Sigma lens keeps ExifTool's spelling; so do the lens
//! texts darktable composes from several tags, for bodies whose `LensModel` is
//! missing.

use std::{collections::HashMap, sync::OnceLock};

type Table = HashMap<(&'static str, &'static str), (&'static str, &'static str)>;

fn table() -> &'static Table {
    static TABLE: OnceLock<Table> = OnceLock::new();
    TABLE.get_or_init(|| {
        include_str!("../data/camera_names.tsv")
            .lines()
            .filter_map(|line| {
                let mut f = line.split('\t');
                Some(((f.next()?, f.next()?), (f.next()?, f.next()?)))
            })
            .collect()
    })
}

/// darktable's `camera_maker` and `camera_model` for an EXIF make and model.
pub(crate) fn make_model(make: &str, model: &str) -> (String, String) {
    let (make, model) = (make.trim(), model.trim());
    match table().get(&(make, model)) {
        Some((m, d)) => ((*m).to_owned(), (*d).to_owned()),
        None => (make.to_owned(), model.to_owned()),
    }
}

/// darktable's lens text for a lens as ExifTool wrote it.
pub(crate) fn lens(name: &str) -> String {
    let name = name.trim();
    if name.starts_with("RF") {
        let rest = if name.as_bytes().get(2) == Some(&b'-') { name.get(4..) } else { name.get(2..) };
        if let Some(rest) = rest {
            let prefix = if name.as_bytes().get(2) == Some(&b'-') { "Canon RF-S " } else { "Canon RF " };
            return format!("{prefix}{rest}");
        }
    }
    if name.starts_with("NIKKOR ") || name.starts_with("TAMRON ") || name.starts_with("VILTROX") {
        let mut text = name.to_owned();
        text[1..7].make_ascii_lowercase();
        return text;
    }
    name.to_owned()
}

/// A camera label ("maker model") in either spelling, as the label of the
/// current one. A label whose maker is not one the table renames stays as it is,
/// which is also what a label already in darktable's spelling does.
pub(crate) fn camera_label(label: &str) -> String {
    let label = label.trim();
    // the maker is everything before the model; try each space as the split,
    // longest maker first, as makers have several words ("NIKON CORPORATION")
    let spaces: Vec<usize> = label.match_indices(' ').map(|(i, _)| i).collect();
    for &at in spaces.iter().rev() {
        let (make, model) = (&label[..at], &label[at + 1..]);
        if let Some((m, d)) = table().get(&(make, model)) {
            return format!("{m} {d}").trim().to_owned();
        }
    }
    label.to_owned()
}

/// A body key (`["maker","model","serial"]` as JSON) with its maker and model in
/// the current spelling; anything else is returned as it is.
pub(crate) fn body_key(key: &str) -> String {
    match serde_json::from_str::<[String; 3]>(key) {
        Ok([make, model, serial]) => {
            let (make, model) = make_model(&make, &model);
            serde_json::to_string(&[make, model, serial]).unwrap_or_else(|_| key.to_owned())
        }
        Err(_) => key.to_owned(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn makers_match_darktable_names() {
        let cases = [
            ("NIKON CORPORATION", "NIKON Z 6", "Nikon", "Z 6"),
            ("NIKON CORPORATION", "NIKON D850", "Nikon", "D850"),
            ("Canon", "Canon EOS R5", "Canon", "EOS R5"),
            ("Canon", "Canon EOS R", "Canon", "EOS R"),
            ("SONY", "ILCE-7M3", "Sony", "ILCE-7M3"),
            ("FUJIFILM", "X-T4", "Fujifilm", "X-T4"),
            ("OLYMPUS IMAGING CORP.", "E-3", "Olympus", "E-3"),
            ("OM Digital Solutions", "OM-1", "OM System", "OM-1"),
            ("OM Digital Solutions", "OM-1MarkII", "OM System", "OM-1 Mark II"),
            ("RICOH IMAGING COMPANY, LTD.", "PENTAX K-3 Mark III", "Pentax", "K-3 Mark III"),
            ("PENTAX", "PENTAX 645Z", "Pentax", "645Z"),
            ("Leica Camera AG", "LEICA M11", "Leica", "M11"),
            ("LEICA CAMERA AG", "LEICA CL", "Leica", "CL"),
            ("Panasonic", "DC-GH5", "Panasonic", "DC-GH5"),
        ];
        for (make, model, want_make, want_model) in cases {
            assert_eq!(make_model(make, model), (want_make.into(), want_model.into()), "{make} {model}");
            // a name already in darktable's spelling stays
            assert_eq!(make_model(want_make, want_model), (want_make.into(), want_model.into()));
        }
        // padding is trimmed; an unknown camera passes through as darktable does
        assert_eq!(make_model(" SONY ", "ILCE-7M3 "), ("Sony".into(), "ILCE-7M3".into()));
        assert_eq!(make_model("Acme", "X1"), ("Acme".into(), "X1".into()));
    }

    #[test]
    fn labels_in_either_spelling_become_the_current_one() {
        assert_eq!(camera_label("NIKON CORPORATION NIKON Z 6"), "Nikon Z 6");
        assert_eq!(camera_label("Nikon Z 6"), "Nikon Z 6");
        assert_eq!(camera_label("OM Digital Solutions OM-1MarkII"), "OM System OM-1 Mark II");
        assert_eq!(camera_label("Leica Camera AG LEICA M11"), "Leica M11");
        assert_eq!(camera_label("Acme X1"), "Acme X1");
        assert_eq!(camera_label(""), "");
        assert_eq!(
            body_key(r#"["NIKON CORPORATION","NIKON Z 6","123"]"#),
            r#"["Nikon","Z 6","123"]"#
        );
        assert_eq!(body_key(""), "");
    }

    #[test]
    fn lenses_follow_darktable_rewrites() {
        assert_eq!(lens("RF24-105mm F4 L IS USM"), "Canon RF 24-105mm F4 L IS USM");
        assert_eq!(lens("RF-S18-150mm F3.5-6.3 IS STM"), "Canon RF-S 18-150mm F3.5-6.3 IS STM");
        assert_eq!(lens("NIKKOR Z 24-70mm f/4 S"), "Nikkor Z 24-70mm f/4 S");
        assert_eq!(lens("TAMRON 28-75mm F/2.8"), "Tamron 28-75mm F/2.8");
        assert_eq!(lens("VILTROX AF 85mm"), "Viltrox AF 85mm");
        assert_eq!(lens("  FE 24-70mm F2.8 GM  "), "FE 24-70mm F2.8 GM");
        assert_eq!(lens("Canon RF 50mm F1.8 STM"), "Canon RF 50mm F1.8 STM");
        assert_eq!(lens(""), "");
        // idempotent
        for name in ["RF24-105mm F4 L IS USM", "NIKKOR Z 24-70mm f/4 S"] {
            assert_eq!(lens(&lens(name)), lens(name));
        }
    }
}
