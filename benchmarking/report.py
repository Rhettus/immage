# after a run: SUMMARY.md from the latest run (and its change since the one
# before), and dashboard/data.js from every run and GUI report, so the
# dashboard opens offline from file://.
#   python3 -I benchmarking/report.py
import argparse
import datetime
import glob
import json
import os
import statistics
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
# python3 -I leaves the script's own folder off the path
sys.path.insert(0, HERE)
import compare  # noqa: E402
RESULTS = os.path.join(HERE, "results")
GUI = os.path.join(RESULTS, "gui")


def med(xs):
    xs = [x for x in xs if x is not None]
    return statistics.median(xs) if xs else None


def fmt(v, unit=" ms"):
    if v is None:
        return "-"
    return f"{v:,.0f}{unit}" if v >= 100 else f"{v:.1f}{unit}"


def pick(run, mode, scenario, step=None, **match):
    out = []
    for r in run["records"]:
        if r["mode"] != mode or r["scenario"] != scenario:
            continue
        if step is not None and r["step"] != step:
            continue
        if any(r.get(k) != v for k, v in match.items()):
            continue
        out.append(r)
    return out


def headline(run, mode):
    """median across the photos of each headline step"""
    m = compare.metric
    sliders_full = [m(r) for r in pick(run, mode, "sliders", size="full")]
    sliders_draft = [m(r) for r in pick(run, mode, "sliders", size="draft")]
    return [
        ("Open to first frame", med(m(r) for r in pick(run, mode, "open", "first frame"))),
        ("Slider frame, full size (median of all sliders)", med(sliders_full)),
        ("Slider frame, drag draft (median of all sliders)", med(sliders_draft)),
        ("Slowest slider frame, full size", max((x for x in sliders_full if x is not None), default=None)),
        ("Release after a drag (full frame)", med(m(r) for r in pick(run, mode, "roi", "full (release)"))),
        ("Idle base render (3072 px)", med(m(r) for r in pick(run, mode, "roi", "base (idle)"))),
        ("Zoom to 100%", med(m(r) for r in pick(run, mode, "zoom", "100% (first)"))),
        ("Pan at 100%", med(m(r) for r in pick(run, mode, "zoom", "100% pan"))),
        ("Hover preview (1600 px)", med(m(r) for r in pick(run, mode, "preview", "preview 1600px"))),
        ("Full-size JPEG export", med(m(r) for r in pick(run, mode, "export"))),
    ]


def slider_table(run, modes):
    controls = []
    for r in run["records"]:
        if r["scenario"] == "sliders" and r.get("control") not in controls:
            controls.append(r.get("control"))
    rows = []
    for c in controls:
        row = [c]
        for mode in modes:
            for size in ("full", "draft"):
                row.append(med(compare.metric(r) for r in pick(run, mode, "sliders", control=c, size=size)))
        rows.append(row)
    rows.sort(key=lambda r: -(r[1] or 0))
    return rows


def module_costs(run, mode):
    """each module's median ms when a full-size slider frame recomputes it"""
    per = {}
    for r in pick(run, mode, "sliders", size="full"):
        for op, ms in r["modules_ms"].items():
            per.setdefault(op, []).append(ms)
    return sorted(((op, med(v), len(v)) for op, v in per.items()), key=lambda x: -x[1])


def alternatives(run, mode):
    groups = {}
    for r in pick(run, mode, "modules"):
        groups.setdefault(r["job"], []).append((r["candidate"], r["immage"], med([r["own_ms"]["p50"]]) if r.get("own_ms") else None))
    # across photos: median per candidate
    out = {}
    for job in groups:
        cands = {}
        for name, imm, ms in groups[job]:
            cands.setdefault((name, imm), []).append(ms)
        out[job] = [(name, imm, med(v)) for (name, imm), v in cands.items()]
    return out


def gui_reports(folder=GUI):
    out = []
    for p in sorted(glob.glob(os.path.join(folder, "*.json"))):
        try:
            with open(p) as f:
                g = json.load(f)
            g["id"] = os.path.splitext(os.path.basename(p))[0]
            out.append(g)
        except (OSError, ValueError):
            pass
    return out


def summary(runs, guis):
    run = runs[-1]
    env = run["env"]
    modes = env["modes"]
    names = {"cpu": "CPU", "opencl": "OpenCL (GPU)", "split": "App (CPU + GPU base and export)"}
    L = ["# Benchmark summary", "",
         "Generated by `benchmarking/report.py` from the latest run; do not edit by hand.",
         "The interactive view is [dashboard/index.html](dashboard/index.html) (open it from disk).", "",
         f"- **Run** `{run['id']}`, {env['at']}, {env.get('seconds', '?')} s",
         f"- **Machine** {env['sysinfo'].get('machdep.cpu.brand_string', env['machine'])}, "
         f"{int(env['sysinfo'].get('hw.memsize', 0)) // 2**30} GB, {env['os']}",
         f"- **Build** git `{env['git']['sha']}` on `{env['git']['branch']}`{' (uncommitted changes)' if env['git']['dirty'] else ''}, "
         f"{env['build'].get('CMAKE_BUILD_TYPE', '?')}",
         f"- **Corpus** `{env['corpus']}`: " + ", ".join(f"{c['name']} ({c.get('sensor', ['?', '?'])[0]}×{c.get('sensor', ['?', '?'])[1]})" for c in run["corpus"]),
         f"- **Viewer** {env['view'][0]}×{env['view'][1]}, drafts {env['draft'][0]}×{env['draft'][1]}, "
         f"{env['repeat']} samples per step"]
    if env.get("note"):
        L.append(f"- **Note** {env['note']}")
    th = env.get("thermal")
    if th and th.get("first_ms"):
        L.append(f"- **Thermal** canary render {th['first_ms']} ms at the start, {th['last_ms']} ms at the end, "
                 f"worst {th['worst_ratio']}× the start; {th['cooldown_s']:.0f} s spent cooling"
                 + (f"; macOS warnings: {'; '.join(th['pmset'])}" if th.get("pmset") else "; no macOS thermal warnings"))
    L += ["", "## Headline (median across photos, wall time of the engine request)", "",
          "| step | " + " | ".join(names[m] for m in modes) + " |", "|---|" + "---:|" * len(modes)]
    heads = {m: headline(run, m) for m in modes}
    for i, (label, _) in enumerate(heads[modes[0]]):
        L.append(f"| {label} | " + " | ".join(fmt(heads[m][i][1]) for m in modes) + " |")

    L += ["", "## Sliders: one frame per move (median across photos)", "",
          "| control | " + " | ".join(f"{names[m]} full | {names[m]} draft" for m in modes) + " |",
          "|---|" + "---:|" * (2 * len(modes))]
    for row in slider_table(run, modes):
        L.append(f"| {row[0]} | " + " | ".join(fmt(v) for v in row[1:]) + " |")

    heavy = [r["step"] for r in run["records"] if r["scenario"] == "heavy"]
    if heavy:
        L += ["", "## A heavy edit: Grain, Texture, Sharpening and denoise on (median across photos)", "",
              "| step | " + " | ".join(names[m] for m in modes) + " |", "|---|" + "---:|" * len(modes)]
        for step in dict.fromkeys(heavy):
            L.append(f"| {step} | " + " | ".join(fmt(med(compare.metric(r) for r in pick(run, m, "heavy", step)))
                                                 for m in modes) + " |")

    longs = [r["step"] for r in run["records"] if r["scenario"] == "longdrag"]
    if longs:
        L += ["", "## A long drag's release (median across photos)", "",
              "The frame on release, after a drag of 40 frames or 4. Before 0.20 a drag's frames were on the main",
              "pipe, and after some 30 of them its release reran from the raw.", "",
              "| step | " + " | ".join(names[m] for m in modes) + " |", "|---|" + "---:|" * len(modes)]
        for step in dict.fromkeys(longs):
            L.append(f"| {step} | " + " | ".join(fmt(med(compare.metric(r) for r in pick(run, m, "longdrag", step)))
                                                 for m in modes) + " |")

    masks = [r for r in run["records"] if r["scenario"] == "masks"]
    if masks:
        models = ("chain", "shared")
        L += ["", "## Masks: an instance each (chain) against shared instances (median across photos)", "",
              "| step | " + " | ".join(f"{names[m]} {x}" for m in modes for x in models) + " |",
              "|---|" + "---:|" * (2 * len(modes))]
        steps = dict.fromkeys(r["step"].replace(", chain,", ",").replace(", shared,", ",")
                              for r in masks if r.get("model") in models)
        for step in steps:
            n, rest = step.split(", ", 1)
            cells = [fmt(med(compare.metric(r) for r in pick(run, m, "masks", f"{n}, {x}, {rest}")))
                     for m in modes for x in models]
            L.append(f"| {step} | " + " | ".join(cells) + " |")
        for m in modes:
            diffs = [r for r in pick(run, m, "masks") if r.get("diff")]
            for step in dict.fromkeys(r["step"] for r in diffs):
                ds = [r["diff"] for r in diffs if r["step"] == step]
                L.append(f"\n{names[m]}, {step}: shared differs from chain by mean "
                         f"{med(d['mean'] for d in ds):.2f}, p99 {med(d['p99'] for d in ds):.0f}, "
                         f"max {max(d['max'] for d in ds)} of 255")

    for m in modes:
        costs = module_costs(run, m)[:12]
        if costs:
            L += ["", f"## Costliest modules when recomputed ({names[m]}, full-size frame)", "",
                  "| module | median ms | frames |", "|---|---:|---:|"]
            L += [f"| {op} | {fmt(ms, '')} | {n} |" for op, ms, n in costs]

    alts = alternatives(run, "cpu" if "cpu" in modes else modes[0])
    if alts:
        L += ["", "## Immage's modules and their alternatives (own time per full-size frame, CPU)", "",
              "| job | module | ms | vs Immage's |", "|---|---|---:|---:|"]
        for job, cands in alts.items():
            base = next((ms for name, imm, ms in cands if imm), None)
            for name, imm, ms in cands:
                rel = "" if imm or not base or ms is None else f"{ms / base:.2f}×"
                L.append(f"| {job} | {'**' + name + '**' if imm else name} | {fmt(ms, '')} | {rel} |")

    over = {m: {r["step"]: compare.metric(r) for r in pick(run, m, "overhead")} for m in modes}
    if any(over.values()):
        L += ["", "## Cost of measuring (`-d perf`)", ""]
        for m in modes:
            o = over[m]
            if o.get("with -d perf") and o.get("without -d perf"):
                L.append(f"- {names[m]}: {fmt(o['with -d perf'])} with, {fmt(o['without -d perf'])} without")

    if guis:
        g = guis[-1]
        L += ["", f"## GUI benchmark `{g['id']}`", "",
              (f"Machine {m.get('host') or '?'}, {m.get('cpu') or '?'} (id {m.get('id') or '?'}). "
               if (m := g.get("machine")) else "") +
              f"Photo {g.get('photo')}, viewer {g['viewport']['width']}×{g['viewport']['height']} "
              f"(dpr {g['viewport']['dpr']}), drag drafts {'on' if g.get('dragDrafts') else 'off'}"
              + (f", Preview {g['preview']}" if g.get("preview") else "")
              + (f", frames by {'shared memory' if g['transport'] == 'shared' else 'invoke'}" if g.get("transport") else "")
              + ".", "",
              "| step | frames | p50 ms | p95 ms | largest stage |", "|---|---:|---:|---:|---|"]
        for s in g["summary"]:
            top = max(s["stages"].items(), key=lambda kv: kv[1])
            L.append(f"| {s['label']} | {s['frames']} | {fmt(s['p50'], '')} | {fmt(s['p95'], '')} | {top[0]} {fmt(top[1])} |")

    prev = compare.previous(runs[:-1], run)
    L += ["", "## Change since the previous run with the same photos", ""]
    L.append(compare.markdown(prev, run, compare.diff(prev, run), limit=10).strip() if prev
             else "None yet: this is the first run over these photos.")

    L += ["", "## Reading these results next time", "",
          "1. This file first.",
          "2. `python3 -I benchmarking/compare.py` diffs the last two runs; every run is",
          "   `results/<date>_<git sha>_<host>/run.json` (`records`: one per mode, photo,",
          "   scenario and step, with p50/p95 wall, pipeline, write and set times and",
          "   per-module ms).",
          "3. GUI reports are `results/gui/gui-*.json`: per-frame stage timings from the app.",
          f"", f"_generated {datetime.datetime.now().astimezone().isoformat(timespec='seconds')}_", ""]
    return "\n".join(L)


def main():
    ap = argparse.ArgumentParser(description="SUMMARY.md and the dashboard's data from the recorded runs")
    ap.add_argument("--results", default=RESULTS, help="runs folder (default benchmarking/results)")
    ap.add_argument("--out", default=HERE, help="where SUMMARY.md and dashboard/data.js go (default benchmarking/)")
    args = ap.parse_args()
    runs = [compare.load(p) for p in compare.runs(args.results)]
    guis = gui_reports(os.path.join(args.results, "gui"))
    if not runs:
        raise SystemExit(f"no runs in {args.results}: run bench.py first")
    with open(os.path.join(args.out, "SUMMARY.md"), "w") as f:
        f.write(summary(runs, guis))
    os.makedirs(os.path.join(args.out, "dashboard"), exist_ok=True)
    data = {"generated": datetime.datetime.now().astimezone().isoformat(timespec="seconds"),
            "runs": runs, "gui": guis}
    with open(os.path.join(args.out, "dashboard", "data.js"), "w") as f:
        f.write("// generated by benchmarking/report.py; the dashboard reads it from file://\n")
        f.write("window.BENCH = ")
        json.dump(data, f, separators=(",", ":"))
        f.write(";\n")
    print(f"SUMMARY.md and dashboard/data.js from {len(runs)} runs and {len(guis)} GUI reports")


if __name__ == "__main__":
    main()
